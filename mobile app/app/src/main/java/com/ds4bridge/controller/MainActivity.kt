/**
 * Parses pairing QR codes generated by `ds4_udp_receiver.py` (e.g. `ds4udp://192.168.1.42:26760`
 * or plain `192.168.1.42:26760`).
 */
fun parseQrPairingPayload(raw: String): Pair<String, Int>? {
    val cleaned = raw.trim().removePrefix("ds4udp://").removePrefix("http://")
    val parts = cleaned.split(":")
    if (parts.isEmpty()) return null
    val ip = parts[0].trim()
    val port = parts.getOrNull(1)?.toIntOrNull() ?: 26760
    if (ip.isBlank()) return null
    return ip to port
}

class MainActivity : ComponentActivity() {

    private val gyroConfigRef = AtomicReference(GyroConfig())
    private val touchStateRef = AtomicReference(ControllerState())
    private lateinit var gyroProcessor: GyroProcessor
    private lateinit var hapticsManager: HapticsAndRumbleManager
    private lateinit var udpSender: UdpSenderThread
    private lateinit var connectionKeeper: ConnectionKeeper
    private val stickSettingsRef = AtomicReference(StickSettings())

    /** True while the app is paused / unfocused / being left: the sender then streams neutral frames only. */
    @Volatile private var neutralHold = false

    // Scratch buffers touched only by the sender thread (no allocation per frame)
    private val leftShaped = FloatArray(2)
    private val rightShaped = FloatArray(2)
    private val gyroOut = FloatArray(2)

    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)

        // Keep screen awake & hide Android system status/navigation bars for fullscreen immersion
        window.addFlags(WindowManager.LayoutParams.FLAG_KEEP_SCREEN_ON)
        WindowCompat.setDecorFitsSystemWindows(window, false)
        WindowInsetsControllerCompat(window, window.decorView).apply {
            hide(WindowInsetsCompat.Type.systemBars())
            systemBarsBehavior = WindowInsetsControllerCompat.BEHAVIOR_SHOW_TRANSIENT_BARS_BY_SWIPE
        }

        var calibrationState by mutableStateOf(GyroCalibrationState())
        var liveRateHz by mutableFloatStateOf(0f)
        var liveSeq by mutableLongStateOf(0L)
        var transportMode by mutableStateOf(TransportMode.WIFI_UDP)
        var liveRttMs by mutableFloatStateOf(-1f)
        var netError by mutableStateOf<String?>(null)
        var networkNotice by mutableStateOf<String?>(null)

        val initialSettings = AppSettingsStore.load(this)
        gyroConfigRef.set(initialSettings.gyroConfig)
        stickSettingsRef.set(initialSettings.stickSettings)

        hapticsManager = HapticsAndRumbleManager(this).apply {
            rumbleEnabled = initialSettings.rumbleEnabled
            buttonHapticTapEnabled = initialSettings.buttonHapticTapEnabled
        }

        gyroProcessor = GyroProcessor(
            context = this,
            configRef = gyroConfigRef,
            onCalibrationUpdated = { calibrationState = it },
            onDriftDetected = {
                runOnUiThread {
                    Toast.makeText(
                        this,
                        "Gyro drift detected. Put the phone flat and still, then tap Recalibrate gyro in Settings.",
                        Toast.LENGTH_LONG
                    ).show()
                }
            }
        )

        // The 120Hz sender merges the latest multi-touch state with the latest 200Hz+ gyro sample
        // and automatically switches between USB (`adb reverse`) and Wi-Fi UDP
        udpSender = UdpSenderThread(
            fillState = { frame -> fillFrame(frame) },
            hapticsManager = hapticsManager,
            onStatsUpdate = { hz, seq, mode, rtt, err ->
                liveRateHz = hz
                liveSeq = seq
                transportMode = mode
                liveRttMs = rtt
                netError = err
            }
        ).apply {
            configureEndpoint(
                host = initialSettings.hostIp,
                port = initialSettings.hostPort,
                rateHz = initialSettings.sendRateHz,
                autoUsb = initialSettings.autoUsbEnabled,
                token = initialSettings.pairingToken
            )
        }

        connectionKeeper = ConnectionKeeper(this) { status, reconnect ->
            networkNotice = status
            if (reconnect) udpSender.requestReconnect()
        }

        udpSender.start()

        setContent {
            MaterialTheme(
                colorScheme = darkColorScheme(
                    primary = androidx.compose.ui.graphics.Color(0xFF22D3EE),
                    onPrimary = androidx.compose.ui.graphics.Color(0xFF042F3A),
                    secondary = androidx.compose.ui.graphics.Color(0xFF8B5CF6),
                    tertiary = androidx.compose.ui.graphics.Color(0xFF34D399),
                    background = androidx.compose.ui.graphics.Color(0xFF070A14),
                    surface = androidx.compose.ui.graphics.Color(0xFF0D1226),
                    surfaceVariant = androidx.compose.ui.graphics.Color(0xFF1B2142),
                    onBackground = androidx.compose.ui.graphics.Color(0xFFE2E8F0),
                    onSurface = androidx.compose.ui.graphics.Color(0xFFE2E8F0),
                    outline = androidx.compose.ui.graphics.Color(0xFF2E3560),
                    error = androidx.compose.ui.graphics.Color(0xFFFB7185)
                )
            ) {
                Ds4AppRoot(
                    initialSettings = initialSettings,
                    touchStateRef = touchStateRef,
                    gyroConfigRef = gyroConfigRef,
                    gyroProcessor = gyroProcessor,
                    hapticsManager = hapticsManager,
                    calibrationState = calibrationState,
                    liveRateHz = liveRateHz,
                    transportMode = transportMode,
                    liveRttMs = liveRttMs,
                    netError = netError ?: networkNotice,
                    stickSettings = initialSettings.stickSettings,
                    onUpdateStickSettings = { stickSettingsRef.set(it) },
                    onTriggerCalibration = { gyroProcessor.startCalibration() },
                    onUpdateEndpoint = { ip, port, token, hz, autoUsb ->
                        udpSender.configureEndpoint(ip, port, hz, autoUsb, token)
                    },
                    onRunRealConnectionTest = { ip, port, useUsb, token, onResult ->
                        udpSender.runRealConnectionTest(ip, port, useUsb, token, 2000, onResult)
                    }
                )
            }
        }
    }

    /**
     * Sender-thread callback: merges the latest touch snapshot with the shaped sticks and the latest gyro
     * sample into the reusable [frame]. No allocation here (the touch snapshot object is created by the
     * touch handler, not by this 120 Hz loop).
     */
    private fun fillFrame(frame: MutableControllerState) {
        if (neutralHold) {
            frame.setNeutral()
            frame.gyroX = 0f; frame.gyroY = 0f; frame.gyroZ = 0f
            frame.accelX = 0f; frame.accelY = 0f; frame.accelZ = 9.81f
            return
        }
        val touch = touchStateRef.get()
        val sticks = stickSettingsRef.get()

        StickMath.shape(touch.lx / 32767f, touch.ly / 32767f, sticks.left, leftShaped)
        StickMath.shape(touch.rx / 32767f, touch.ry / 32767f, sticks.right, rightShaped)

        gyroProcessor.computeInto(touch.buttonsMask, gyroOut)
        if (gyroProcessor.targetsLeftStick()) {
            leftShaped[0] += gyroOut[0]; leftShaped[1] += gyroOut[1]
        } else {
            rightShaped[0] += gyroOut[0]; rightShaped[1] += gyroOut[1]
        }

        frame.buttonsMask = touch.buttonsMask
        frame.lx = ControllerState.floatAxisToInt16(leftShaped[0])
        frame.ly = ControllerState.floatAxisToInt16(leftShaped[1])
        frame.rx = ControllerState.floatAxisToInt16(rightShaped[0])
        frame.ry = ControllerState.floatAxisToInt16(rightShaped[1])
        frame.l2 = touch.l2
        frame.r2 = touch.r2
        frame.gyroX = gyroProcessor.filteredGyroX
        frame.gyroY = gyroProcessor.filteredGyroY
        frame.gyroZ = gyroProcessor.filteredGyroZ
        frame.accelX = gyroProcessor.latestAccelX
        frame.accelY = gyroProcessor.latestAccelY
        frame.accelZ = gyroProcessor.latestAccelZ
    }

    private fun goNeutral() {
        neutralHold = true
        touchStateRef.set(ControllerState())
    }

    override fun onStart() {
        super.onStart()
        connectionKeeper.start()
    }

    override fun onResume() {
        super.onResume()
        gyroProcessor.start()
        if (hasWindowFocus()) neutralHold = false
    }

    override fun onWindowFocusChanged(hasFocus: Boolean) {
        super.onWindowFocusChanged(hasFocus)
        if (hasFocus) neutralHold = false else goNeutral() // notification shade, split-screen, dialogs
    }

    override fun onPause() {
        goNeutral()          // all inputs released, gyro zeroed, the PC sees neutral immediately
        gyroProcessor.stop() // sensors off while not visible
        hapticsManager.stopRumble()
        super.onPause()
    }

    override fun onStop() {
        connectionKeeper.stop() // release Wi-Fi + wake locks while in background
        super.onStop()
    }

    override fun onDestroy() {
        goNeutral()
        udpSender.stop()
        gyroProcessor.stop()
        hapticsManager.stopRumble()
        super.onDestroy()
    }
}

/**
 * Root navigation host switching between:
 *  1. [StartScreen] — Full options menu before gameplay (Connect, USB/Wi-Fi, Rate, Profiles, Gyro, Haptics, Start)
 *  2. [GameplayScreen] — Pure fullscreen image-only controller (`painterResource(R.drawable.*)`) with
 *     a single top-right semi-transparent gear icon that slides out the 40%-width Settings Side Panel.
 */
@Composable
fun Ds4AppRoot(
    initialSettings: PersistedAppSettings,
    touchStateRef: AtomicReference<ControllerState>,
    gyroConfigRef: AtomicReference<GyroConfig>,
    gyroProcessor: GyroProcessor,
    hapticsManager: HapticsAndRumbleManager,
    calibrationState: GyroCalibrationState,
    liveRateHz: Float,
    transportMode: TransportMode,
    liveRttMs: Float,
    netError: String?,
    stickSettings: StickSettings,
    onUpdateStickSettings: (StickSettings) -> Unit,
    onTriggerCalibration: () -> Unit,
    onUpdateEndpoint: (String, Int, String, Int, Boolean) -> Unit,
    onRunRealConnectionTest: (String, Int, Boolean, String, (Result<Float>) -> Unit) -> Unit
) {
    val context = LocalContext.current
    val prefs = remember { context.getSharedPreferences(SETUP_PREFS_NAME, Context.MODE_PRIVATE) }

    var setupCompleted by remember {
        mutableStateOf(prefs.getBoolean(KEY_SETUP_COMPLETED, false))
    }
    var wizardStep by remember {
        mutableIntStateOf(prefs.getInt(KEY_SETUP_STEP, 1).coerceIn(1, 7))
    }

    var inGameplay by remember { mutableStateOf(false) }
    var launchInEditMode by remember { mutableStateOf(false) }

    var hostIp by remember { mutableStateOf(initialSettings.hostIp) }
    var hostPort by remember { mutableIntStateOf(initialSettings.hostPort) }
    var pairingToken by remember { mutableStateOf(initialSettings.pairingToken) }
    var sendRateHz by remember { mutableIntStateOf(initialSettings.sendRateHz) }
    var autoUsbEnabled by remember { mutableStateOf(initialSettings.autoUsbEnabled) }

    var gyroConfig by remember { mutableStateOf(initialSettings.gyroConfig) }
    var currentStickSettings by remember { mutableStateOf(stickSettings) }
    var rumbleEnabled by remember { mutableStateOf(initialSettings.rumbleEnabled) }
    var buttonTapEnabled by remember { mutableStateOf(initialSettings.buttonHapticTapEnabled) }

    val profiles = remember { mutableStateListOf(*initialSettings.profiles.toTypedArray()) }
    var activeProfileIndex by remember {
        val idx = initialSettings.profiles.indexOfFirst { it.id == initialSettings.activeProfileId }
        mutableIntStateOf(if (idx >= 0) idx else 0)
    }

    if (!setupCompleted) {
        SetupWizardScreen(
            initialStep = wizardStep,
            onStepChanged = { wizardStep = it },
            hostIp = hostIp,
            hostPort = hostPort,
            pairingToken = pairingToken,
            sendRateHz = sendRateHz,
            transportMode = transportMode,
            liveRttMs = liveRttMs,
            netError = netError,
            gyroConfig = gyroConfig,
            onUpdateGyroConfig = {
                gyroConfig = it
                gyroConfigRef.set(it)
                AppSettingsStore.saveGyroConfig(context, it)
            },
            calibrationState = calibrationState,
            onTriggerCalibration = onTriggerCalibration,
            liveTiltOffset = gyroProcessor.peekOffset(),
            profiles = profiles,
            activeProfileIndex = activeProfileIndex,
            onSelectProfileIndex = {
                activeProfileIndex = it
                AppSettingsStore.saveProfiles(context, profiles, profiles[it].id)
            },
            onSendTestButtonTap = { btnMask ->
                hapticsManager.triggerButtonPressTap()
                touchStateRef.set(ControllerState(buttonsMask = btnMask))
            },
            onApplyEndpoint = { ip, port, token, hz, autoUsb ->
                hostIp = ip
                hostPort = port
                pairingToken = token
                sendRateHz = hz
                autoUsbEnabled = autoUsb
                AppSettingsStore.saveEndpoint(context, ip, port, token, hz, autoUsb)
                onUpdateEndpoint(ip, port, token, hz, autoUsb)
            },
            onRunRealConnectionTest = onRunRealConnectionTest,
            onFinishSetup = {
                touchStateRef.set(ControllerState())
                setupCompleted = true
            }
        )
    } else if (!inGameplay) {
        StartScreen(
            hostIp = hostIp,
            hostPort = hostPort,
            pairingToken = pairingToken,
            sendRateHz = sendRateHz,
            autoUsbEnabled = autoUsbEnabled,
            transportMode = transportMode,
            liveRateHz = liveRateHz,
            liveRttMs = liveRttMs,
            netError = netError,
            profiles = profiles,
            activeProfileIndex = activeProfileIndex,
            onSelectProfileIndex = {
                activeProfileIndex = it
                AppSettingsStore.saveProfiles(context, profiles, profiles[it].id)
            },
            onOpenEditLayout = {
                launchInEditMode = true
                inGameplay = true
            },
            onImportProfileJson = { rawJson ->
                when (val r = ProfileSchema.parse(rawJson)) {
                    is ProfileParseResult.Ok -> {
                        // never overwrite an existing profile id: import as a new copy
                        val unique = if (profiles.any { it.id == r.profile.id }) {
                            r.profile.copy(id = r.profile.id + "_" + System.currentTimeMillis().toString(36))
                        } else r.profile
                        profiles.add(unique)
                        activeProfileIndex = profiles.lastIndex
                        AppSettingsStore.saveProfiles(context, profiles, unique.id)
                        val note = if (r.warnings.isEmpty()) "Profile imported." else "Imported with fixes: " + r.warnings.joinToString("; ")
                        Toast.makeText(context, note, Toast.LENGTH_LONG).show()
                        true
                    }
                    is ProfileParseResult.Error -> {
                        Toast.makeText(context, "Import failed: " + r.message, Toast.LENGTH_LONG).show()
                        false
                    }
                }
            },
            gyroConfig = gyroConfig,
            onUpdateGyroConfig = {
                gyroConfig = it
                gyroConfigRef.set(it)
                AppSettingsStore.saveGyroConfig(context, it)
            },
            stickSettings = currentStickSettings,
            onUpdateStickSettings = {
                currentStickSettings = it
                onUpdateStickSettings(it)
                AppSettingsStore.saveStickSettings(context, it)
            },
            calibrationState = calibrationState,
            onTriggerCalibration = onTriggerCalibration,
            rumbleEnabled = rumbleEnabled,
            buttonHapticTapEnabled = buttonTapEnabled,
            onUpdateHaptics = { r, t ->
                rumbleEnabled = r
                buttonTapEnabled = t
                hapticsManager.rumbleEnabled = r
                hapticsManager.buttonHapticTapEnabled = t
                AppSettingsStore.saveHaptics(context, r, t)
            },
            onApplyEndpoint = { ip, port, token, hz, autoUsb ->
                hostIp = ip
                hostPort = port
                pairingToken = token
                sendRateHz = hz
                autoUsbEnabled = autoUsb
                AppSettingsStore.saveEndpoint(context, ip, port, token, hz, autoUsb)
                onUpdateEndpoint(ip, port, token, hz, autoUsb)
            },
            onStartGameplay = {
                launchInEditMode = false
                inGameplay = true
            },
            onRunSetupAgain = {
                wizardStep = 1
                prefs.edit().putInt(KEY_SETUP_STEP, 1).apply()
                setupCompleted = false
            },
            onResetSetup = {
                prefs.edit()
                    .putBoolean(KEY_SETUP_COMPLETED, false)
                    .putInt(KEY_SETUP_STEP, 1)
                    .apply()
                wizardStep = 1
                setupCompleted = false
            }
        )
    } else {
        GameplayScreen(
            touchStateRef = touchStateRef,
            hapticsManager = hapticsManager,
            profiles = profiles,
            activeProfileIndex = activeProfileIndex,
            onSelectProfileIndex = {
                activeProfileIndex = it
                AppSettingsStore.saveProfiles(context, profiles, profiles[it].id)
            },
            onUpdateProfileElements = { updatedElements ->
                val current = profiles[activeProfileIndex]
                val updatedProfile = current.copy(elements = updatedElements)
                profiles[activeProfileIndex] = updatedProfile
                AppSettingsStore.saveProfiles(context, profiles, updatedProfile.id)
            },
            gyroConfig = gyroConfig,
            onUpdateGyroConfig = {
                gyroConfig = it
                gyroConfigRef.set(it)
                AppSettingsStore.saveGyroConfig(context, it)
            },
            transportMode = transportMode,
            liveRttMs = liveRttMs,
            liveRateHz = liveRateHz,
            initialEditMode = launchInEditMode,
            onDisconnectToStart = {
                touchStateRef.set(ControllerState())
                launchInEditMode = false
                inGameplay = false
            }
        )
    }
}
