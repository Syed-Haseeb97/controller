data class QrPairingInfo(
    val ip: String,
    val port: Int,
    val token: String
)

/**
 * Strictly parses `ds4udp://<ip>:<port>?token=<token>` QR codes generated by the PC receiver.
 * Returns Result.failure with a plain-language message if the QR code is invalid.
 */
fun parseDs4QrUri(raw: String): Result<QrPairingInfo> {
    val trimmed = raw.trim()
    if (!trimmed.startsWith("ds4udp://", ignoreCase = true)) {
        return Result.failure(
            IllegalArgumentException("Invalid QR code: expected a ds4udp://ip:port?token=... pairing code.")
        )
    }
    return try {
        val uri = Uri.parse(trimmed)
        val host = uri.host?.trim().orEmpty()
        val port = if (uri.port != -1) uri.port else 26760
        val token = uri.getQueryParameter("token")?.trim().orEmpty()
        if (host.isEmpty()) {
            return Result.failure(IllegalArgumentException("QR code is missing the PC IP address."))
        }
        if (port !in 1..65535) {
            return Result.failure(IllegalArgumentException("QR code contains an invalid UDP port ($port)."))
        }
        Result.success(QrPairingInfo(ip = host, port = port, token = token))
    } catch (e: Exception) {
        Result.failure(IllegalArgumentException("Could not parse QR code: ${e.localizedMessage ?: "malformed URI"}"))
    }
}

@Composable
fun QrScannerDialog(
    onDismiss: () -> Unit,
    onPaired: (QrPairingInfo) -> Unit
) {
    val context = LocalContext.current
    val lifecycleOwner = LocalLifecycleOwner.current
    var scanError by remember { mutableStateOf<String?>(null) }
    val cameraExecutor = remember { Executors.newSingleThreadExecutor() }

    DisposableEffect(Unit) {
        onDispose {
            cameraExecutor.shutdown()
        }
    }

    Dialog(onDismissRequest = onDismiss) {
        Column(
            modifier = Modifier
                .fillMaxWidth()
                .background(Color(0xFF0D1226), RoundedCornerShape(16.dp))
                .border(1.dp, Color(0xFF1B2142), RoundedCornerShape(16.dp))
                .padding(16.dp),
            verticalArrangement = Arrangement.spacedBy(12.dp)
        ) {
            Row(
                modifier = Modifier.fillMaxWidth(),
                horizontalArrangement = Arrangement.SpaceBetween,
                verticalAlignment = Alignment.CenterVertically
            ) {
                Text(
                    text = "Scan PC Pairing QR Code",
                    color = Color.White,
                    fontSize = 15.sp,
                    fontWeight = FontWeight.Bold
                )
                TextButton(onClick = onDismiss) {
                    Text("Close", color = Color(0xFF94A3B8))
                }
            }

            Box(
                modifier = Modifier
                    .fillMaxWidth()
                    .height(220.dp)
                    .background(Color.Black, RoundedCornerShape(12.dp))
                    .border(1.dp, Color(0xFF2E3560), RoundedCornerShape(12.dp))
            ) {
                AndroidView(
                    modifier = Modifier.fillMaxSize(),
                    factory = { ctx ->
                        val previewView = PreviewView(ctx)
                        val cameraProviderFuture = ProcessCameraProvider.getInstance(ctx)
                        val options = BarcodeScannerOptions.Builder()
                            .setBarcodeFormats(Barcode.FORMAT_QR_CODE)
                            .build()
                        val scanner = BarcodeScanning.getClient(options)

                        cameraProviderFuture.addListener({
                            val cameraProvider = runCatching { cameraProviderFuture.get() }.getOrNull()
                            if (cameraProvider == null) {
                                scanError = "Could not initialize camera provider."
                                return@addListener
                            }
                            val preview = Preview.Builder().build().also {
                                it.surfaceProvider = previewView.surfaceProvider
                            }
                            val analysis = ImageAnalysis.Builder()
                                .setBackpressureStrategy(ImageAnalysis.STRATEGY_KEEP_ONLY_LATEST)
                                .build()

                            analysis.setAnalyzer(cameraExecutor) { imageProxy ->
                                processBarcodeFrame(
                                    imageProxy = imageProxy,
                                    scanner = scanner,
                                    onRawValue = { rawValue ->
                                        val parsed = parseDs4QrUri(rawValue)
                                        parsed.onSuccess { info ->
                                            ContextCompat.getMainExecutor(ctx).execute {
                                                onPaired(info)
                                            }
                                        }.onFailure { err ->
                                            ContextCompat.getMainExecutor(ctx).execute {
                                                scanError = err.message
                                            }
                                        }
                                    }
                                )
                            }

                            try {
                                cameraProvider.unbindAll()
                                cameraProvider.bindToLifecycle(
                                    lifecycleOwner,
                                    CameraSelector.DEFAULT_BACK_CAMERA,
                                    preview,
                                    analysis
                                )
                            } catch (e: Exception) {
                                scanError = "Camera bind failed: ${e.localizedMessage}"
                            }
                        }, ContextCompat.getMainExecutor(ctx))

                        previewView
                    }
                )
            }

            if (scanError != null) {
                Text(
                    text = scanError!!,
                    color = Color(0xFFFDA4AF),
                    fontSize = 12.sp,
                    fontFamily = FontFamily.Monospace
                )
            } else {
                Text(
                    text = "Point the camera at the ds4udp://ip:port?token=... QR code shown in the PC tray app.",
                    color = Color(0xFF94A3B8),
                    fontSize = 11.sp
                )
            }
        }
    }
}

@SuppressLint("UnsafeOptInUsageError")
private fun processBarcodeFrame(
    imageProxy: ImageProxy,
    scanner: com.google.mlkit.vision.barcode.BarcodeScanner,
    onRawValue: (String) -> Unit
) {
    val mediaImage = imageProxy.image
    if (mediaImage == null) {
        imageProxy.close()
        return
    }
    val image = InputImage.fromMediaImage(mediaImage, imageProxy.imageInfo.rotationDegrees)
    scanner.process(image)
        .addOnSuccessListener { barcodes ->
            for (barcode in barcodes) {
                val raw = barcode.rawValue
                if (!raw.isNullOrBlank()) {
                    onRawValue(raw)
                    break
                }
            }
        }
        .addOnCompleteListener {
            imageProxy.close()
        }
}
